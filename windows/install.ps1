#Requires -Version 5.1

# Set DOTFILES environment variable
$env:DOTFILES = Split-Path $PSScriptRoot -Parent
Write-Host "DOTFILES environment variable is set: $env:DOTFILES" -ForegroundColor Green

# Check if PowerShell profile exists and back it up if it does
if (-Not (Test-Path $profile)) {
    Write-Host "PowerShell profile does not exist: $profile" -ForegroundColor Yellow
} else {
    Write-Host "PowerShell profile exists, backing up to $profile.bak" -ForegroundColor Green
    Copy-Item -Path $profile -Destination "$profile.bak" -Force
}

# Write content to the PowerShell profile
$profileContent = @"
# generated by `dotfiles` repository
# This file is automatically generated and should not be edited manually.
# You should regenerate this file by running the `install.ps1` script,
# refer to https://github.com/huiyifyj/dotfiles/blob/main/windows/install.ps1

# Set DOTFILES environment variable for the profile
`$env:DOTFILES = "$env:DOTFILES"
if (-Not (Test-Path `$env:DOTFILES)) {
    Write-Error "DOTFILES environment variable is not set correctly." -ForegroundColor Red
} else {
    # Load PowerShell profile
    . "`$env:DOTFILES\windows\Microsoft.PowerShell_profile.ps1"
}
"@
$profileContent | Out-File -FilePath $profile -Encoding UTF8 -Force
Write-Host "PowerShell profile setted successfully" -ForegroundColor Green
